function initialLocale(): Locale {
  const stored = load('locale');
  if (stored === 'en' || stored === 'de') return stored;
  for (const tag of navigator.languages ?? [navigator.language]) {
    const l = tag.toLowerCase();
    if (l === 'de' || l.startsWith('de-')) return 'de';
    if (l === 'en' || l.startsWith('en-')) return 'en';
  }
  return 'en';
}

export const i18n = $state({ locale: initialLocale() });

export function t(key: string, params: Record<string, string | number> = {}): string {
  const raw = messages[i18n.locale][key] ?? messages.en[key] ?? key;
  return raw.replace(/\{([a-zA-Z]+)\}/g, (m, name: string) => (Object.hasOwn(params, name) ? String(params[name]) : m));
}

export function hasText(key: string): boolean {
  return Object.hasOwn(messages.en, key);
}
